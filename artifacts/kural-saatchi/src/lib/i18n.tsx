export type TranslationKey = keyof typeof translations.en;

interface LanguageContextType {
  lang: Language;
  setLang: (lang: Language) => void;
  toggleLang: () => void;
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
  isTamil: boolean;
  isEnglish: boolean;
}

const LanguageContext = createContext<LanguageContextType | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Language>(() => {
    try {
      const stored = localStorage.getItem('kural-lang');
      if (stored === 'ta' || stored === 'en') return stored;
    } catch {
      // ignore
    }
    return 'ta'; // Default to Tamil as requested
  });

  const setLang = (nextLang: Language) => {
    setLangState(nextLang);
    try {
      localStorage.setItem('kural-lang', nextLang);
    } catch {
      // ignore
    }
  };

  const toggleLang = () => {
    setLang(lang === 'ta' ? 'en' : 'ta');
  };

  useEffect(() => {
    document.documentElement.setAttribute('lang', lang);
    document.title = lang === 'ta' ? 'குறள் சாட்சி — மூலச் சரிபார்ப்பு' : 'Kural Saatchi — Source Verification';
  }, [lang]);

  const t = (key: TranslationKey, params?: Record<string, string | number>): string => {
    const dict = translations[lang] || translations.en;
    let text: string = dict[key] || translations.en[key] || key;
    if (params) {
      for (const [k, v] of Object.entries(params)) {
        text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }
    }
    return text;
  };

  return (
    <LanguageContext.Provider
      value={{
        lang,
        setLang,
        toggleLang,
        t,
        isTamil: lang === 'ta',
        isEnglish: lang === 'en',
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    throw new Error('useLanguage must be used within a LanguageProvider');
  }
  return ctx;
}
